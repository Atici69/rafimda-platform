CREATE TABLE IF NOT EXISTS `ri_invoices` (
  `id_invoice` int(11) NOT NULL AUTO_INCREMENT,
  `idem_key` varchar(80) NOT NULL,
  `kind` varchar(16) NOT NULL DEFAULT 'sale',
  `doc_type` varchar(16) NOT NULL DEFAULT '',
  `issuer_type` varchar(16) NOT NULL DEFAULT 'vendor',
  `id_vendor` int(11) NOT NULL DEFAULT 0,
  `id_order` int(11) NOT NULL DEFAULT 0,
  `id_user` int(11) NOT NULL DEFAULT 0,
  `buyer_type` varchar(16) NOT NULL DEFAULT 'individual',
  `buyer_name` varchar(190) NOT NULL DEFAULT '',
  `buyer_tax_no` varchar(16) NOT NULL DEFAULT '',
  `buyer_tax_office` varchar(120) NOT NULL DEFAULT '',
  `buyer_address` varchar(500) NOT NULL DEFAULT '',
  `buyer_email` varchar(190) NOT NULL DEFAULT '',
  `lines` mediumtext DEFAULT NULL,
  `net_total` decimal(14,2) NOT NULL DEFAULT 0.00,
  `vat_total` decimal(14,2) NOT NULL DEFAULT 0.00,
  `gross_total` decimal(14,2) NOT NULL DEFAULT 0.00,
  `currency` varchar(3) NOT NULL DEFAULT 'TRY',
  `status` varchar(16) NOT NULL DEFAULT 'draft',
  `environment` varchar(8) NOT NULL DEFAULT 'test',
  `integrator` varchar(32) NOT NULL DEFAULT '',
  `ettn` varchar(40) NOT NULL DEFAULT '',
  `invoice_no` varchar(32) NOT NULL DEFAULT '',
  `pdf_file` varchar(120) NOT NULL DEFAULT '',
  `related_invoice` int(11) NOT NULL DEFAULT 0,
  `period` varchar(7) NOT NULL DEFAULT '',
  `last_error` varchar(500) NOT NULL DEFAULT '',
  `created_by` varchar(24) NOT NULL DEFAULT '',
  `sent_at` datetime DEFAULT NULL,
  `date_add` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `date_upd` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id_invoice`),
  UNIQUE KEY `idem_key` (`idem_key`),
  KEY `id_order` (`id_order`),
  KEY `id_vendor` (`id_vendor`),
  KEY `id_user` (`id_user`),
  KEY `status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ri_events` (
  `id_event` int(11) NOT NULL AUTO_INCREMENT,
  `id_invoice` int(11) NOT NULL DEFAULT 0,
  `event` varchar(32) NOT NULL,
  `detail` varchar(1000) NOT NULL DEFAULT '',
  `is_error` tinyint(1) NOT NULL DEFAULT 0,
  `actor` varchar(24) NOT NULL DEFAULT 'system',
  `date_add` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id_event`),
  KEY `id_invoice` (`id_invoice`),
  KEY `is_error` (`is_error`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `ri_accounts` (
  `id_account` int(11) NOT NULL AUTO_INCREMENT,
  `owner_type` varchar(16) NOT NULL DEFAULT 'platform',
  `id_vendor` int(11) NOT NULL DEFAULT 0,
  `integrator` varchar(32) NOT NULL DEFAULT 'test',
  `environment` varchar(8) NOT NULL DEFAULT 'test',
  `username` varchar(190) NOT NULL DEFAULT '',
  `secret_enc` text DEFAULT NULL,
  `efatura_user` varchar(8) NOT NULL DEFAULT 'unknown',
  `status` varchar(16) NOT NULL DEFAULT 'untested',
  `last_error` varchar(500) NOT NULL DEFAULT '',
  `last_test_at` datetime DEFAULT NULL,
  `date_upd` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id_account`),
  UNIQUE KEY `owner` (`owner_type`, `id_vendor`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
